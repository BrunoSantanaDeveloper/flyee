#!/usr/bin/env node
// PreToolUse guard for member-facing content.
//
// Fires on Write/Edit/MultiEdit under modules/<slug>/** (an app) or
// packages/core/assets/** (the harness the CLI writes into member projects).
// Both are read by members and by their AIs, so the reminder is about the
// boundary and the authoring rules. Non-blocking. Pure Node, no shell.

import { extractToolPaths, isCodexHook, normalizeToolPath } from "./lib/tool-paths.mjs";

let raw = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => (raw += chunk));
process.stdin.on("end", () => {
  let input = {};
  try {
    input = JSON.parse(raw || "{}");
  } catch {
    process.exit(0);
  }

  const paths = extractToolPaths(input).map(normalizeToolPath);
  const isApp = paths.some((path) => /(^|\/)modules\/[^/]+\//.test(path) && !/\/tests\//.test(path));
  const isAppTest = paths.some((path) => /(^|\/)modules\/[^/]+\/tests\//.test(path));
  const isCore = paths.some((path) => /(^|\/)packages\/core\/assets\//.test(path));
  const isGeneratedCatalog = paths.some((path) => /(^|\/)(\.claude\/rules\/catalogo\.md|docs\/CATALOGO\.md)$/.test(path));
  if (!isApp && !isCore && !isAppTest && !isGeneratedCatalog) process.exit(0);

  const lines = [];
  if (isGeneratedCatalog) {
    lines.push(
      "GENERATED CATALOG: .claude/rules/catalogo.md and docs/CATALOGO.md are rebuilt from modules/* by `npm run apps -- catalog` after every app change. Do not edit them: change the app (manifest, README, skills, references/interface.md) instead.",
    );
  }
  if (isApp) {
    lines.push(
      "APP (ships to members) — mandatory before this write/edit:",
      "1. Load the `app-author` skill and follow it; the reference is docs/COMO-CRIAR-UM-APP.md. A new app starts at its step 0: the apps catalog (.claude/rules/catalogo.md) decides what to call, reuse or extend instead of rebuilding.",
      "2. Everything under modules/<slug>/ except tests/, .dev/ and *.dev.md is read by the member and their AI: pt-BR first, no internal names, no links the server did not give.",
      "3. `files` in flyee.module.json is generated by `npm run pack`; never hand-edit it. A version bump needs a new `changelog`.",
      "4. SKILL.md frontmatter: `name` equals the folder (lowercase, single hyphens, ≤64), `description` says what and when (≤1024, aim under 400). Relative references resolve from the skill's own folder.",
      "5. Declare every permission (`fs:read`, `fs:write`, `network`, `shell`, `env`) with a reason, and every external credential; keep a mode that works without the key.",
      "6. pt-BR writing (checked after the write and by `validate`): no em dash glued between words, few dashes, no evaluative AI vocabulary or formulas; rewrite with the `humanizer-pt-br` skill. An app that writes text for the member's audience has the AI review it with the core skill `texto-natural` before delivering (`min_core` >=1.3.0).",
    );
  }
  if (isAppTest) {
    lines.push(
      "APP TESTS (operator-only): tests/eval.json never ships. Keep at least one case with prompt, assertions and rubric; turn support failures into cases.",
    );
  }
  if (isCore) {
    lines.push(
      "CORE ASSETS (ship inside the CLI, written into member projects): bilingual, member-facing, no internal tooling names. Bump packages/core/assets/core.json when members should receive the change on `npx flyee update`. The pt-BR writing check runs on every .md here too.",
    );
  }

  const reminder = lines.join("\n");
  const output = isCodexHook(input)
    ? { systemMessage: reminder }
    : { hookSpecificOutput: { hookEventName: "PreToolUse", additionalContext: reminder } };
  process.stdout.write(JSON.stringify(output));
  process.exit(0);
});
