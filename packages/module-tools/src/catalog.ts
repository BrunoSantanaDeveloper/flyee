import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

import { MANIFEST_FILE, shippableFiles } from "./files.ts";
import { parseFrontmatter } from "./frontmatter.ts";
import { type Manifest, readManifest } from "./manifest.ts";
import { listModuleDirs, modulesRoot, repoRoot } from "./paths.ts";
import { type InterfaceInfo, readInterface, referencedApps } from "./relations.ts";

/**
 * The operator's catalog: what every app in modules/ does, what it ships for
 * other apps and who calls whom. Generated, deterministic (no dates, no git
 * state) so CI can check it, and never distributed: it lives in the
 * development harness (`.claude/rules/catalogo.md`, always loaded by the AI
 * working in this repository and mirrored into AGENTS.md for Codex) and in
 * `docs/CATALOGO.md`.
 */

export type CatalogEntry = {
  slug: string;
  version: string;
  type: string;
  trail: string;
  title: string;
  title_en: string | null;
  summary: string;
  about: string;
  compatible_ais: string[];
  skills: { name: string; description: string }[];
  credentials: { env: string; name: string; required: boolean }[];
  permissions: { kind: string; scope: string }[];
  interface: InterfaceInfo | null;
  uses: string[];
  used_by: string[];
};

export const DIGEST_PATH = join(repoRoot, ".claude", "rules", "catalogo.md");
export const DOCUMENT_PATH = join(repoRoot, "docs", "CATALOGO.md");
const GENERATED = "<!-- GENERATED by `npm run apps -- catalog` from modules/*. Do not edit: change the apps and the file follows. -->";

/** The first paragraph of the README after its title: the app in the member's words. */
function readmeAbout(dir: string): string {
  const path = join(dir, "README.md");
  if (!existsSync(path)) return "";
  const lines = readFileSync(path, "utf8").replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((line) => line.startsWith("# "));
  const paragraph: string[] = [];
  for (const line of lines.slice(start + 1)) {
    if (!line.trim()) {
      if (paragraph.length) break;
      continue;
    }
    if (line.startsWith("#")) break;
    paragraph.push(line.trim());
  }
  return paragraph.join(" ");
}

function skillsOf(dir: string): { name: string; description: string }[] {
  return shippableFiles(dir)
    .filter((file) => /^skills\/[^/]+\/SKILL\.md$/.test(file))
    .map((file) => {
      const parsed = parseFrontmatter(readFileSync(join(dir, ...file.split("/")), "utf8"));
      return { name: parsed?.data.name ?? file.split("/")[1], description: parsed?.data.description ?? "" };
    });
}

function entryFor(dir: string, manifest: Manifest): CatalogEntry {
  return {
    slug: basename(dir),
    version: manifest.version,
    type: manifest.type,
    trail: manifest.trail,
    title: manifest.title?.["pt-BR"] ?? basename(dir),
    title_en: manifest.title?.en ?? null,
    summary: manifest.summary?.["pt-BR"] ?? "",
    about: readmeAbout(dir),
    compatible_ais: manifest.compatible_ais ?? [],
    skills: skillsOf(dir),
    credentials: (manifest.external_credentials ?? []).map((credential) => ({
      env: credential.env,
      name: credential.name,
      required: Boolean(credential.required),
    })),
    permissions: (manifest.permissions ?? []).map((permission) => ({ kind: permission.kind, scope: permission.scope })),
    interface: readInterface(dir),
    uses: referencedApps(dir),
    used_by: [],
  };
}

/** Every app of a modules root, with the inverse relation filled in. Apps whose manifest cannot be read are skipped. */
export function buildCatalog(root: string = modulesRoot): CatalogEntry[] {
  const entries: CatalogEntry[] = [];
  for (const dir of listModuleDirs(root)) {
    const { manifest } = readManifest(join(dir, MANIFEST_FILE));
    if (manifest) entries.push(entryFor(dir, manifest));
  }
  for (const entry of entries) {
    entry.used_by = entries.filter((other) => other.uses.includes(entry.slug)).map((other) => other.slug);
  }
  return entries;
}

const cell = (value: string) => value.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const list = (values: string[]) => (values.length ? values.map((value) => `\`${value}\``).join(", ") : "—");

function interfaceCell(entry: CatalogEntry): string {
  if (!entry.interface) return "—";
  const version = entry.interface.version === null ? "" : ` v${entry.interface.version}`;
  const entryScript = entry.interface.entry ? ` \`${entry.interface.entry}\`` : "";
  return `sim${version}${entryScript}`;
}

/** The always-loaded digest: one row per app, enough to recognize what exists and where to read more. */
export function renderDigest(entries: CatalogEntry[]): string {
  const header = [
    "# Apps catalog",
    "",
    GENERATED,
    "",
    "Every app that exists in `modules/`, so that a request to create or change an app starts from what is already built. Before designing a new app, run step 0 of the `app-author` skill against this table: which apps the new one should call at runtime, which help to build it now, and which already do part of the job. Details per app in `docs/CATALOGO.md`, in its `README.md` and, when it serves other apps, in `references/interface.md`. To use an app from this chat, follow the `apps` skill: it is linked into the workspace and run from there, never inside this repository.",
    "",
  ];
  if (entries.length === 0) return `${[...header, "No app exists yet (`modules/_template` is the starting point).", ""].join("\n")}`;
  const rows = entries.map((entry) => {
    const skills = entry.skills.map((skill) => skill.name);
    return `| \`${entry.slug}\` ${entry.version} | ${entry.type} · ${entry.trail} | ${cell(entry.summary)} | ${list(skills)} | ${interfaceCell(entry)} | ${list(entry.uses)} | ${list(entry.used_by)} |`;
  });
  return [
    ...header,
    "| App | Type · trail | What it delivers | Skills | Serves other apps | Uses | Used by |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

/** The full operator catalog in Portuguese, one section per app. */
export function renderDocument(entries: CatalogEntry[]): string {
  const out = [
    "# Catálogo de apps",
    "",
    GENERATED,
    "",
    "Material do operador: nunca é distribuído. Cada app aparece com o que entrega, as skills que a IA do integrante carrega, as chaves que ele fornece, o que o app oferece a outros apps e quem chama quem. O que um app usa é lido dos arquivos que ele distribui: um app usa outro quando cita o caminho instalado dele (`.flyee/modules/<slug>/`).",
    "",
  ];
  if (entries.length === 0) {
    out.push("Nenhum app ainda. O ponto de partida é `npm run apps -- new <slug> --type <tipo> --trail <trilha>`.", "");
    return out.join("\n");
  }
  out.push("| App | Versão | Tipo | Trilha | Usa | Usado por |", "|---|---|---|---|---|---|");
  for (const entry of entries) {
    out.push(`| [${cell(entry.title)}](#${entry.slug}) | ${entry.version} | ${entry.type} | ${entry.trail} | ${list(entry.uses)} | ${list(entry.used_by)} |`);
  }
  out.push("");
  for (const entry of entries) {
    out.push(`## ${entry.slug}`, "");
    out.push(`**${entry.title}**${entry.title_en ? ` (${entry.title_en})` : ""} · versão ${entry.version} · ${entry.type} · trilha ${entry.trail} · testado em ${list(entry.compatible_ais)}`, "");
    if (entry.summary) out.push(`> ${cell(entry.summary)}`, "");
    if (entry.about) out.push(entry.about, "");
    out.push("**Skills**", "");
    for (const skill of entry.skills) out.push(`- \`${skill.name}\`: ${cell(skill.description)}`);
    if (entry.skills.length === 0) out.push("- nenhuma");
    out.push("");
    if (entry.credentials.length) {
      out.push("**Chaves externas**", "");
      for (const credential of entry.credentials) {
        out.push(`- \`${credential.env}\` (${credential.name}), ${credential.required ? "obrigatória" : "opcional"}`);
      }
      out.push("");
    }
    if (entry.interface) {
      out.push("**Serve outros apps**", "");
      out.push(`- Guia: \`modules/${entry.slug}/references/interface.md\`${entry.interface.version === null ? "" : `, interface v${entry.interface.version}`}`);
      if (entry.interface.entry) out.push(`- Entrada: \`node .flyee/modules/${entry.slug}/${entry.interface.entry} <comando> --json\``);
      if (entry.interface.commands.length) out.push(`- Comandos nos exemplos: ${list(entry.interface.commands)}`);
      out.push("");
    }
    out.push(`**Usa** ${list(entry.uses)} · **Usado por** ${list(entry.used_by)}`, "");
    if (entry.permissions.length) {
      out.push("**Permissões declaradas**", "");
      for (const permission of entry.permissions) out.push(`- ${permission.kind}: ${cell(permission.scope)}`);
      out.push("");
    }
  }
  return out.join("\n");
}

export type CatalogWrite = { stale: string[]; written: string[] };

/**
 * Writes the digest and the document when they differ from what modules/
 * produces; `check` only reports. A changed digest regenerates the Codex
 * mirror, because AGENTS.md includes every rule file.
 */
export function writeCatalog(options: { check?: boolean; root?: string; digestPath?: string; documentPath?: string; syncHarness?: boolean } = {}): CatalogWrite {
  const entries = buildCatalog(options.root);
  const targets: [string, string][] = [
    [options.digestPath ?? DIGEST_PATH, renderDigest(entries)],
    [options.documentPath ?? DOCUMENT_PATH, renderDocument(entries)],
  ];
  const stale: string[] = [];
  const written: string[] = [];
  for (const [path, content] of targets) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    stale.push(path);
    if (!options.check) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content, "utf8");
      written.push(path);
    }
  }
  const digestChanged = written.includes(options.digestPath ?? DIGEST_PATH);
  if (digestChanged && (options.syncHarness ?? true)) {
    spawnSync(process.execPath, [join(repoRoot, "scripts", "sync-agent-harness.mjs")], { cwd: repoRoot, encoding: "utf8" });
  }
  return { stale, written };
}
