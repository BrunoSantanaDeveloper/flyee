export type MessageKey = keyof (typeof MESSAGES)["pt-BR"];

/** Every message of a language, for the copy test. */
export function allMessages(locale: Locale): Record<string, string> {
  return { ...MESSAGES[locale === "en" ? "en" : "pt-BR"] };
}

export function t(ctx: Pick<Context, "locale">, key: MessageKey, params: Record<string, string | number> = {}): string {
  const table = MESSAGES[ctx.locale === "en" ? "en" : "pt-BR"] as Record<string, string>;
  const template = table[key] ?? (MESSAGES["pt-BR"] as Record<string, string>)[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function localeOf(value: unknown): Locale {
  return value === "en" ? "en" : "pt-BR";
}
